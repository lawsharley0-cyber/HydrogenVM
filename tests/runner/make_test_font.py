"""Regenerate TestFont.hpp with fonttools; no third-party font assets used."""
from io import BytesIO
from pathlib import Path
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen

builder = FontBuilder(1000, isTTF=True)
builder.setupGlyphOrder([".notdef", "space", "A"])
builder.setupCharacterMap({32: "space", 65: "A"})
glyphs = {}
for name in [".notdef", "space", "A"]:
    pen = TTGlyphPen(None)
    if name == "A":
        pen.moveTo((100, 0))
        pen.lineTo((300, 700))
        pen.lineTo((500, 0))
        pen.closePath()
    glyphs[name] = pen.glyph()
builder.setupGlyf(glyphs)
builder.setupHorizontalMetrics({g: (600, 0) for g in glyphs})
builder.setupHorizontalHeader(ascent=800, descent=-200, lineGap=100)
builder.setupNameTable({"familyName": "HVM Test", "styleName": "Regular",
                       "uniqueFontIdentifier": "HVMTest-Regular",
                       "fullName": "HVM Test Regular", "psName": "HVMTest-Regular"})
builder.setupOS2(sTypoAscender=800, sTypoDescender=-200, sTypoLineGap=100,
                usWinAscent=800, usWinDescent=200)
builder.setupPost()
builder.setupMaxp()
builder.font["head"].created = builder.font["head"].modified = 2082844800
out = BytesIO()
builder.font.save(out)
data = out.getvalue()
lines = [", ".join(f"0x{b:02x}" for b in data[i:i+16]) for i in range(0, len(data), 16)]
Path(__file__).with_name("TestFont.hpp").write_text(
    "// Generated by make_test_font.py. Original geometric test font, CC0.\n"
    "#pragma once\nstatic const uint8_t kTestFont[] = {\n    " + ",\n    ".join(lines) + "\n};\n")
