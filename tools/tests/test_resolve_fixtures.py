"""tools/resolve_fixtures.py: the integrity-checked way scripts find private fixtures (#204).

Every fixture here is generated bytes in a temporary directory: no real game, no
repository IPA, no network.
"""
import contextlib
import hashlib
import io
import json
import os
import sys
import tempfile
import unittest

TOOLS = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, TOOLS)

import resolve_fixtures  # noqa: E402

REPO = os.path.abspath(os.path.join(TOOLS, ".."))
REAL_MANIFEST = os.path.join(TOOLS, "compat_harness", "manifests", "apps.json")


def _write_store(root, files):
    """files: {name: bytes}. Returns {name: sha256} for the manifest."""
    os.makedirs(os.path.join(root, "ipas"), exist_ok=True)
    digests = {}
    for name, data in files.items():
        with open(os.path.join(root, "ipas", name), "wb") as f:
            f.write(data)
        digests[name] = hashlib.sha256(data).hexdigest()
    return digests


def _manifest(path, entries):
    apps = [{"id": ident, "sha256": digest, "fixtureRelPath": f"ipas/{name}", "optional": False}
            for ident, name, digest in entries]
    with open(path, "w", encoding="utf-8") as f:
        json.dump({"schemaVersion": 1, "apps": apps}, f)


class ResolveFixturesTests(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.root = os.path.join(self._tmp.name, "store")
        self.manifest = os.path.join(self._tmp.name, "apps.json")
        digests = _write_store(self.root, {"one.ipa": b"generated-one", "two.ipa": b"generated-two"})
        _manifest(self.manifest, [("one", "one.ipa", digests["one.ipa"]),
                                  ("two", "two.ipa", digests["two.ipa"])])

    def test_resolves_in_the_requested_order_from_the_store(self):
        paths, problems = resolve_fixtures.resolve(["two", "one"], fixture_root=self.root,
                                                   manifest_path=self.manifest)
        self.assertEqual(problems, [])
        self.assertEqual([os.path.basename(p) for p in paths], ["two.ipa", "one.ipa"])
        for p in paths:
            self.assertTrue(os.path.realpath(p).startswith(os.path.realpath(self.root) + os.sep))

    def test_no_store_is_an_error_never_a_fallback(self):
        paths, problems = resolve_fixtures.resolve(["one"], fixture_root=None, manifest_path=self.manifest)
        self.assertEqual(paths, [])
        self.assertIn("HVM_FIXTURE_ROOT", problems[0])

    def test_changed_bytes_are_refused(self):
        with open(os.path.join(self.root, "ipas", "one.ipa"), "ab") as f:
            f.write(b"x")
        paths, problems = resolve_fixtures.resolve(["one"], fixture_root=self.root, manifest_path=self.manifest)
        self.assertEqual(paths, [])
        self.assertTrue(any("one" in p and "sha256" in p for p in problems), problems)

    def test_missing_file_and_unknown_id_are_named(self):
        os.remove(os.path.join(self.root, "ipas", "two.ipa"))
        paths, problems = resolve_fixtures.resolve(["two", "nope"], fixture_root=self.root,
                                                   manifest_path=self.manifest)
        self.assertEqual(paths, [])
        self.assertTrue(any(p.startswith("two:") for p in problems), problems)
        self.assertTrue(any(p.startswith("nope:") for p in problems), problems)

    def test_a_repository_copy_is_never_used(self):
        # The real manifest still names the three grandfathered files in the repo root.
        # With a store set that does not hold them they must stay unresolved.
        empty = os.path.join(self._tmp.name, "empty-store")
        os.makedirs(empty)
        paths, problems = resolve_fixtures.resolve(["angry-birds"], fixture_root=empty,
                                                   manifest_path=REAL_MANIFEST)
        self.assertEqual(paths, [])
        self.assertTrue(problems and problems[0].startswith("angry-birds:"), problems)

    def test_main_prints_one_path_per_line_or_nothing_with_exit_2(self):
        out, err = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            code = resolve_fixtures.main(["--fixture-root", self.root, "--manifest", self.manifest, "one", "two"])
        self.assertEqual(code, 0)
        self.assertEqual([os.path.basename(p) for p in out.getvalue().split("\n") if p], ["one.ipa", "two.ipa"])

        out, err = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            code = resolve_fixtures.main(["--fixture-root", self.root, "--manifest", self.manifest, "one", "nope"])
        self.assertEqual(code, 2)
        self.assertEqual(out.getvalue(), "")
        self.assertIn("nope", err.getvalue())


if __name__ == "__main__":
    unittest.main()
