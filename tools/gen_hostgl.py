#!/usr/bin/env python3
"""Generate src/runtime/gl/HostGLTable.inc from tools/hostgl_spec.txt.

The .inc file holds, for every GL entry point the host backend forwards:
  * HOSTGL_FN(name, ret, (host params)) X-macro rows for the function table,
  * one guest-facing wrapper `hg_<name>(Ctx&, guest args...)` per non-'!' row,
  * HOSTGL_REG(name) rows used to register the `_<name>` symbols.

Run:  python3 tools/gen_hostgl.py   (CI checks that the output is up to date)
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SPEC = os.path.join(ROOT, "tools", "hostgl_spec.txt")
OUT = os.path.join(ROOT, "src", "runtime", "gl", "HostGLTable.inc")

HOST = {"E": "uint32_t", "U": "uint32_t", "BF": "uint32_t", "I": "int32_t", "S": "int32_t", "B": "uint8_t",
        "F": "float", "IP": "intptr_t", "SP": "intptr_t", "p": "const void*", "w": "void*", "cs": "const char*",
        "o": "const void*", "e": "const void*", "Y": "void*", "L": "uint64_t"}
GUEST = {"E": "uint32_t", "U": "uint32_t", "BF": "uint32_t", "I": "int32_t", "S": "int32_t", "B": "uint32_t",
         "F": "float", "IP": "int32_t", "SP": "int32_t", "p": "GuestPtr", "w": "GuestPtr", "cs": "GuestPtr",
         "o": "GuestPtr", "e": "GuestPtr", "Y": "uint32_t", "L": "uint64_t"}
RET_HOST = {"v": "void", "E": "uint32_t", "U": "uint32_t", "I": "int32_t", "B": "uint8_t", "P": "void*", "Y": "void*", "cs": "const char*"}
RET_GUEST = {"v": "void", "E": "uint32_t", "U": "uint32_t", "I": "int32_t", "B": "bool", "P": "uint32_t", "Y": "uint32_t", "cs": "uint32_t"}
LINE = re.compile(r"^(!?)(\w+)\s+(\w+)\((.*)\)\s*(\[\w+\])?\s*$")


def conv(t, a):
    if t == "cs":
        return f"static_cast<const char*>(HG_PTR(x, {a}))"
    if t in ("p", "w"):
        return f"HG_PTR(x, {a})"
    if t == "o":
        return f"hgArrayPtr(x, {a})"
    if t == "e":
        return f"hgIndexPtr(x, {a})"
    if t == "B":
        return f"uint8_t({a} & 0xFF)"
    if t in ("IP", "SP"):
        return f"intptr_t(uint32_t({a}))"
    return a


def main():
    rows = []
    for raw in open(SPEC):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        m = LINE.match(line)
        if not m:
            sys.exit(f"bad spec line: {line}")
        manual, ret, name, args, _tag = m.groups()
        params = []
        for part in [p.strip() for p in args.split(",") if p.strip()]:
            t, a = part.split()
            params.append((t, a))
        rows.append((bool(manual), ret, name, params))

    out = ["// Generated by tools/gen_hostgl.py from tools/hostgl_spec.txt. Do not edit.", ""]
    out.append("#ifdef HOSTGL_TABLE")
    for manual, ret, name, params in rows:
        host_params = ", ".join(HOST[t] for t, _ in params) or "void"
        out.append(f"HOSTGL_FN({name}, {RET_HOST[ret]}, ({host_params}))")
    out.append("#endif")
    out.append("")
    out.append("#ifdef HOSTGL_WRAPPERS")
    for manual, ret, name, params in rows:
        if manual:
            continue
        gargs = "".join(f", {GUEST[t]} a_{a}" for t, a in params)
        call = ", ".join(conv(t, "a_" + a) for t, a in params)
        rg = RET_GUEST[ret]
        argnames = ", ".join("a_" + a for t, a in params)
        out.append(f"{rg} hg_{name}(Ctx& x{gargs}) {{")
        out.append(f"    HostContext* hc = hgCurrent(x);")
        out.append(f"    if (!hc || !hc->fn.{name}) {{ hgMissing(x, hc, \"{name}\"); return{' ' + rg + '()' if rg != 'void' else ''}; }}")
        if name.startswith("glUniform"):
            out.append(f"    if (hc->currentProgram == 0) return{' ' + rg + '()' if rg != 'void' else ''};")

        if name in ("glGenTextures", "glGenBuffers", "glGenFramebuffers", "glGenRenderbuffers"):
            if name == "glGenTextures": out.append(f"    if (hc && hc->guestSharegroup) if (auto it = S(x.proc).telemetry.find(hc->guestSharegroup); it != S(x.proc).telemetry.end()) it->second->textures += a_n;")
            elif name == "glGenBuffers": out.append(f"    if (hc && hc->guestSharegroup) if (auto it = S(x.proc).telemetry.find(hc->guestSharegroup); it != S(x.proc).telemetry.end()) it->second->buffers += a_n;")
            elif name == "glGenFramebuffers": out.append(f"    if (hc && hc->guestSharegroup) if (auto it = S(x.proc).telemetry.find(hc->guestSharegroup); it != S(x.proc).telemetry.end()) it->second->framebuffers += a_n;")
            elif name == "glGenRenderbuffers": out.append(f"    if (hc && hc->guestSharegroup) if (auto it = S(x.proc).telemetry.find(hc->guestSharegroup); it != S(x.proc).telemetry.end()) it->second->renderbuffers += a_n;")

        if name in ("glDeleteTextures", "glDeleteBuffers", "glDeleteFramebuffers", "glDeleteRenderbuffers"):
            if name == "glDeleteTextures":
                out.append(f"    if (hc && hc->guestSharegroup != 0) {{")
                out.append(f"        if (auto it = S(x.proc).telemetry.find(hc->guestSharegroup); it != S(x.proc).telemetry.end()) {{")
                out.append(f"            std::lock_guard<std::mutex> lock(S(x.proc).telemetryMu);")
                out.append(f"            GuestPtr ptr = a_textures;")
                out.append(f"            for(int i=0; i<a_n; i++) {{")
                out.append(f"                uint32_t tex = x.proc.mem().read<uint32_t>(ptr);")
                out.append(f"                if (auto sz = S(x.proc).textureBytes.find(tex); sz != S(x.proc).textureBytes.end()) {{")
                out.append(f"                    it->second->estimatedBytes -= sz->second;")
                out.append(f"                    S(x.proc).textureBytes.erase(sz);")
                out.append(f"                }}")
                out.append(f"                ptr += 4;")
                out.append(f"            }}")
                out.append(f"            it->second->textures -= a_n;")
                out.append(f"        }}")
                out.append(f"    }}")
            elif name == "glDeleteBuffers": out.append(f"    if (hc && hc->guestSharegroup) if (auto it = S(x.proc).telemetry.find(hc->guestSharegroup); it != S(x.proc).telemetry.end()) it->second->buffers -= a_n;")
            elif name == "glDeleteFramebuffers": out.append(f"    if (hc && hc->guestSharegroup) if (auto it = S(x.proc).telemetry.find(hc->guestSharegroup); it != S(x.proc).telemetry.end()) it->second->framebuffers -= a_n;")
            elif name == "glDeleteRenderbuffers": out.append(f"    if (hc && hc->guestSharegroup) if (auto it = S(x.proc).telemetry.find(hc->guestSharegroup); it != S(x.proc).telemetry.end()) it->second->renderbuffers -= a_n;")

        if name == "glCreateProgram":
            out.append(f"    if (hc && hc->guestSharegroup) if (auto it = S(x.proc).telemetry.find(hc->guestSharegroup); it != S(x.proc).telemetry.end()) it->second->programs++;")

        if name == "glDeleteProgram":
            out.append(f"    if (hc && hc->guestSharegroup) if (auto it = S(x.proc).telemetry.find(hc->guestSharegroup); it != S(x.proc).telemetry.end()) it->second->programs--;")

        if name == "glCreateShader":
            out.append(f"    if (hc && hc->guestSharegroup) if (auto it = S(x.proc).telemetry.find(hc->guestSharegroup); it != S(x.proc).telemetry.end()) it->second->shaders++;")

        if name == "glDeleteShader":
            out.append(f"    if (hc && hc->guestSharegroup) if (auto it = S(x.proc).telemetry.find(hc->guestSharegroup); it != S(x.proc).telemetry.end()) it->second->shaders--;")

        if name == "glBindTexture":
            out.append(f"    if (a_target == 0x0DE1 /* GL_TEXTURE_2D */) hc->boundTexture2D = a_texture;")
        if ret == "v":
            out.append(f"    hc->fn.{name}({call});")
            if name.startswith("glUniform"):
                out.append(f"    hc->fn.glGetError();")
            out.append(f"    if (hgDebug) hgAfter(x, hc, \"{name}\", [&] {{ return hgArgs({argnames}); }});")
        else:
            out.append(f"    auto r = hc->fn.{name}({call});")
            out.append(f"    if (hgDebug) hgAfter(x, hc, \"{name}\", [&] {{ return hgArgs({argnames}); }});")
            out.append("    return r != 0;" if ret == "B" else "    return r;")
        out.append("}")
    out.append("#endif")
    out.append("")
    out.append("#ifdef HOSTGL_REGISTER")
    for manual, ret, name, params in rows:
        out.append(f"HOSTGL_REG({name})")
    out.append("#endif")
    text = "\n".join(out) + "\n"
    if "--check" in sys.argv:
        if not os.path.exists(OUT) or open(OUT).read() != text:
            sys.exit("HostGLTable.inc is out of date: run python3 tools/gen_hostgl.py")
        return
    with open(OUT, "w") as f:
        f.write(text)
    print(f"wrote {OUT}: {len(rows)} entry points")


if __name__ == "__main__":
    main()
